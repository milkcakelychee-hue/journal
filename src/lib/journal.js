const DAY = 864e5;
export const qIndex = (k, off = 0) => ((Math.floor(fromKey(k).getTime() / DAY) + off) % 100 + 100) % 100;

const esc = s => String(s).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
export const Q = '\u0001';

// ข้อความ → HTML ในกระดาษ
export function toHtml(text, editable = false) {
  const lines = (text || '').split('\n'), ce = editable ? ' contenteditable="false"' : '';
  return lines.map((l, i) => l.startsWith(Q) ? `<span class="tw-ql"${ce}>${esc(l.slice(1))}</span>`
    : esc(l) + (i < lines.length - 1 && !lines[i + 1].startsWith(Q) ? '\n' : '')).join('');
}

// กระดาษที่พิมพ์ (contenteditable) → ข้อความ
export function fromEl(el) {
  let out = '';
  const walk = n => {
    for (const c of n.childNodes) {
      if (c.nodeType === 3) out += c.data.replace(/\u200b/g, '');
      else if (c.classList?.contains('tw-ql')) { if (out && !out.endsWith('\n')) out += '\n'; out += Q + c.textContent + '\n'; }
      else if (c.tagName === 'BR') out += '\n';
      else { if ((c.tagName === 'DIV' || c.tagName === 'P') && out && !out.endsWith('\n')) out += '\n'; walk(c); }
    }
  };
  walk(el);
  return out.replace(/\n+$/, '');
}
export const isBlank = t => !(t || '').split('\n').some(l => !l.startsWith(Q) && l.trim());
